// Play in every camera mode. Each one takes a different rendering path, and a throw inside
// update() or draw() escapes gameLoop before it can schedule the next frame — the game freezes.
const MODES = ['topdown', 'thirdperson', 'firstperson', 'fp3d'];
let allOk = true;
for (const mode of MODES) {
  try {
    vm.runInNewContext(`
      chosenClass = CLASSES[0];
      playerName = 'SmokeTest';
      gameRunning = false;
      cameraMode = ${JSON.stringify(mode)};
      startGame();
      cameraMode = ${JSON.stringify(mode)};
      __clock = 0; _simLast = 0; _simAcc = 0;
      __startX = player.x; __startY = player.y; __startAng = player.angle;
      __path = 0; __lx = player.x; __ly = player.y;
      keys = {}; keys['w'] = true;
      var __dirs = ['w','d','s','a'];
      mouse.x = 700; mouse.y = 200;
      // Sweep the view as a real player would, so a single building cannot block the whole run —
      // walking into a wall and stopping is correct behaviour, not a failure. This also drives the
      // look path: in every mode but top-down, W is relative to where you are facing.
      for (var __f = 0; __f < 300; __f++) {
        // Rotate BOTH the facing and which key is held. Top-down moves screen-relative, so turning
        // alone cannot free a player wedged against a structure — and walking into something and
        // stopping is correct behaviour, not a failure to detect.
        if (__f % 40 === 0) {
          player.angle += 0.9;
          keys = {}; keys[__dirs[(__f / 40) % 4]] = true;
        }
        __clock += 16.7; gameLoop(__clock);
        // Distance actually WALKED, not displacement — turning makes you circle back, and walking
        // into a building and stopping is correct behaviour rather than a failure.
        __path += Math.hypot(player.x - __lx, player.y - __ly); __lx = player.x; __ly = player.y;
      }
      __moved = __path;
      __mons = monsters.length; __parts = particles.length;
    `, ctx, { filename:'game.js', timeout:30000 });
  } catch (e) {
    allOk = false;
    console.log(mode.padEnd(13), 'THREW');
    console.log('   ', e.name + ': ' + e.message);
    const m = (e.stack||'').match(/game\.js:(\d+)/);
    if (m) console.log('    at script line ' + m[1] + ': ' + code.split('\n')[m[1]-1].trim().slice(0,100));
    continue;
  }
  const moved = vm.runInNewContext('__moved', ctx);
  const mons  = vm.runInNewContext('__mons', ctx);
  const parts = vm.runInNewContext('__parts', ctx);
  const ok = moved > 100;
  if (!ok) allOk = false;
  console.log(mode.padEnd(13), 'walked', String(Math.round(moved)).padStart(5),
              'units  monsters', String(mons).padStart(3),
              '  particles', String(parts).padStart(4), ok ? '  PASS' : '  FAIL  did not move');
}
console.log('\n' + (allOk ? 'SMOKE TEST PASS — all camera modes run and move'
                          : 'SMOKE TEST FAIL'));
process.exit(allOk ? 0 : 1);
